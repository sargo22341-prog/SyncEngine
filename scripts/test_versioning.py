"""Version bump and release notes tests, on isolated copies only."""
import shutil
import subprocess
import tempfile
import tomllib
import unittest
from pathlib import Path

import versioning

LOCK = """# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "patched"
version = "0.1.0"
"""


def workspace(root, lock=LOCK, crlf=False):
    (root / "app").mkdir()
    (root / "patched").mkdir()
    newline = "\r\n" if crlf else "\n"
    (root / "Cargo.toml").write_bytes((
        '[workspace]\nmembers = ["app", "patched"]\n\n[workspace.package]\n'
        'license = "GPL-3.0-only"\nversion = "0.1.0"\n\n[workspace.dependencies]\n'
        'serde = { version = "0.1.0" }\n').replace("\n", newline).encode())
    (root / "app/Cargo.toml").write_text('[package]\nname = "app"\nversion.workspace = true\n')
    (root / "patched/Cargo.toml").write_text('[package]\nname = "patched"\nversion = "0.1.0"\n')
    (root / "Cargo.lock").write_bytes(lock.replace("\n", newline).encode())


class VersioningTests(unittest.TestCase):
    def test_next_version(self):
        self.assertEqual(versioning.next_version("1.2.3", "patch"), "1.2.4")
        self.assertEqual(versioning.next_version("1.2.3", "minor"), "1.3.0")
        self.assertEqual(versioning.next_version("1.2.3", "major"), "2.0.0")
        for current, part in (("1.2", "patch"), ("1.2.3", "build")):
            with self.assertRaises(ValueError):
                versioning.next_version(current, part)

    def test_bump_only_touches_workspace_version_and_local_lock_entries(self):
        for crlf in (False, True):
            with tempfile.TemporaryDirectory() as tmp:
                root = Path(tmp)
                workspace(root, crlf=crlf)
                self.assertEqual(versioning.bump("minor", root), ("0.1.0", "0.2.0"))
                manifest = tomllib.loads((root / "Cargo.toml").read_text())
                self.assertEqual(manifest["workspace"]["package"]["version"], "0.2.0")
                self.assertEqual(manifest["workspace"]["dependencies"]["serde"]["version"], "0.1.0")
                lock = tomllib.loads((root / "Cargo.lock").read_text())
                versions = {p["name"]: p["version"] for p in lock["package"]}
                self.assertEqual(versions, {"app": "0.2.0", "serde": "0.1.0", "patched": "0.1.0"})
                self.assertNotIn(b"\r\n", (root / "Cargo.lock").read_bytes())

    def test_stale_lock_is_refused_before_any_lock_write(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            workspace(root, lock=LOCK.replace('name = "app"\nversion = "0.1.0"', 'name = "app"\nversion = "0.0.9"'))
            before = [(root / name).read_bytes() for name in ("Cargo.toml", "Cargo.lock")]
            with self.assertRaises(ValueError):
                versioning.bump("patch", root)
            self.assertEqual([(root / name).read_bytes() for name in ("Cargo.toml", "Cargo.lock")], before)

    def test_repository_lock_matches_workspace_version(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            manifest = tomllib.loads((versioning.ROOT / "Cargo.toml").read_text(encoding="utf-8"))
            for name in ("Cargo.toml", "Cargo.lock"):
                shutil.copy(versioning.ROOT / name, root / name)
            for member in manifest["workspace"]["members"]:
                (root / member).mkdir(parents=True)
                shutil.copy(versioning.ROOT / member / "Cargo.toml", root / member / "Cargo.toml")
            current = manifest["workspace"]["package"]["version"]
            self.assertEqual(versioning.bump("patch", root), (current, versioning.next_version(current, "patch")))

    def test_notes_extract_and_reset_keep_header(self):
        with tempfile.TemporaryDirectory() as tmp:
            notes = Path(tmp) / "RELEASE_NOTES.md"
            notes.write_bytes(b"# Title\r\nhow-to\r\n<!-- notes -->\r\n\r\n- one\r\n\r\n- two\r\n\r\n")
            self.assertEqual(versioning.notes(notes), "- one\n\n- two")
            versioning.reset_notes(notes)
            self.assertEqual(notes.read_text(), "# Title\nhow-to\n<!-- notes -->\n\n")
            self.assertEqual(versioning.notes(notes), "")

    def test_missing_marker_is_refused(self):
        with tempfile.TemporaryDirectory() as tmp:
            notes = Path(tmp) / "RELEASE_NOTES.md"
            notes.write_text("# Title\n- one\n")
            for action in (versioning.notes, versioning.reset_notes):
                with self.assertRaises(ValueError):
                    action(notes)
            self.assertEqual(notes.read_text(), "# Title\n- one\n")

    @unittest.skipUnless(shutil.which("git"), "git missing")
    def test_release_commit_is_identical_in_two_clones(self):
        with tempfile.TemporaryDirectory() as tmp:
            origin = Path(tmp) / "origin"
            repository(origin, "# Notes\n<!-- notes -->\n\n- fixed\n")
            results = []
            for name in ("windows", "linux"):
                clone = Path(tmp) / name
                subprocess.run(["git", "clone", "--quiet", str(origin), str(clone)], check=True)
                results.append(versioning.release("patch", Path(tmp) / f"{name}.md", clone))
                self.assertEqual((Path(tmp) / f"{name}.md").read_text(), "- fixed\n")
                self.assertEqual(versioning.notes(clone / "RELEASE_NOTES.md"), "")
            self.assertEqual(results[0], results[1])
            self.assertEqual(results[0][0], "0.1.1")
            message = subprocess.run(["git", "-C", str(Path(tmp) / "linux"), "log", "-1", "--format=%s"],
                                     check=True, capture_output=True, text=True).stdout.strip()
            self.assertEqual(message, "Version 0.1.1 [skip ci]")

    @unittest.skipUnless(shutil.which("git"), "git missing")
    def test_release_refuses_a_modified_checkout(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            repository(root, "<!-- notes -->\n")
            (root / "app/Cargo.toml").write_text("# edited\n")
            with self.assertRaises(ValueError):
                versioning.release("patch", root / "notes.md", root)
            self.assertIn('version = "0.1.0"', (root / "Cargo.toml").read_text())


def repository(root, release_notes):
    root.mkdir(exist_ok=True)
    workspace(root)
    (root / "RELEASE_NOTES.md").write_text(release_notes)
    git = ["git", "-c", "core.safecrlf=false", "-c", "user.name=fixture", "-c", "user.email=fixture@example.invalid",
           "-c", "commit.gpgsign=false", "-C", str(root)]
    subprocess.run([*git, "init", "--quiet"], check=True)
    subprocess.run([*git, "add", "."], check=True)
    subprocess.run([*git, "commit", "--quiet", "-m", "fixture"], check=True)


if __name__ == "__main__":
    unittest.main()
